// Regression tests for the content audit (system 11): BUG_AUDIT.md → "11. Content data & schemas".
import { describe, expect, it } from 'vitest';
import { readFileSync, readdirSync } from 'node:fs';
import {
  CITIES, CITY, EVENTS, EVENT, FOUNDERS, INDUSTRIES, INV, INVESTMENTS, SCENARIOS, SPECIALS, TERM, applyFx, endTurn, fill, goalTarget, goalText, money,
  newGame, startScenario, type Fx,
} from '../engine/src/index';
import { opts } from './helpers';
import { validate } from './schema';

const url = (p: string) => new URL('../' + p, import.meta.url);
const load = (p: string) => JSON.parse(readFileSync(url(p), 'utf8'));
const source = (dir: string): string[] =>
  readdirSync(url(dir), { withFileTypes: true }).flatMap((f) => (f.isDirectory() ? source(`${dir}/${f.name}`) : f.name.endsWith('.ts') ? [readFileSync(url(`${dir}/${f.name}`), 'utf8')] : []));

describe('audit: every content file has a schema that covers it', () => {
  // winrates.json is generated by the balance harness, not written by hand
  const files = readdirSync(url('data')).filter((f) => f.endsWith('.json') && f !== 'winrates.json');
  for (const f of files) {
    it(`${f} validates against schemas/${f.replace('.json', '.schema.json')}`, () => {
      expect(validate(load('data/' + f), load(`data/schemas/${f.replace('.json', '.schema.json')}`))).toEqual([]);
    });
  }

  it('the schemas reject the mistakes they exist to catch', () => {
    const ev = load('data/schemas/events.schema.json');
    const card = (over: object) => [{ id: 'x', cat: 'market', title: 'T', text: 'x', lesson: 'x', opts: [{ label: 'a', hint: 'b', out: [{ text: 'c' }] }], ...over }];
    // a misspelt condition was ignored by evalCond, so the card fired for everyone
    expect(validate(card({ cond: { minRevenue: 100 } }), ev).join()).toContain('unexpected "minRevenue"');
    expect(validate(card({ cond: { ind: 'saas' } }), ev).join()).toContain('expected array');
    expect(validate(card({ opts: [{ label: 'a', hint: 'b', req: { cashS: 1, minTurns: 3 }, out: [{ text: 'c' }] }] }), ev).join()).toContain('unexpected "minTurns"');
    // an unknown boost stat never passes, so the outcome it favours silently loses its edge
    expect(validate(card({ opts: [{ label: 'a', hint: 'b', out: [{ text: 'c', boost: ['charisma', 50, 2] }] }] }), ev).join()).toContain('charisma');
    // a misspelt investment effect was read as 0
    const inv = { ...load('data/investments.json')[0], fx: { inputcost: -5 } };
    expect(validate([inv], load('data/schemas/investments.schema.json')).join()).toContain('unexpected "inputcost"');
    // an industry missing a number the engine multiplies by becomes NaN everywhere
    const { elast: _e, ...noElast } = load('data/industries.json')[0];
    expect(validate([noElast], load('data/schemas/industries.schema.json')).join()).toContain('missing "elast"');
    const { blurb: _b, ...noBlurb } = load('data/cities.json').cities[0];
    expect(validate({ ...load('data/cities.json'), cities: [noBlurb] }, load('data/schemas/cities.schema.json')).join()).toContain('missing "blurb"');
  });
});

describe('audit: cross-references resolve', () => {
  it('scenarios name a real industry, city, founder and setup', () => {
    const setups = readFileSync(url('engine/src/scenarios.ts'), 'utf8');
    for (const s of SCENARIOS) {
      expect(INDUSTRIES[s.industry], s.id).toBeTruthy();
      expect(CITY[s.city], s.id).toBeTruthy();
      expect(FOUNDERS.some((f) => f.id === s.founder), s.id).toBe(true);
      expect(setups.includes(`\n  ${s.setup}: (g`), `${s.id}: setup ${s.setup}`).toBe(true);
    }
  });

  it('investment start and failure effects, and every condition, name things that exist', () => {
    const FX = new Set(EVENTS.flatMap((e) => e.opts.flatMap((o) => o.out.flatMap((x) => (x.fx ?? []).map((f) => f[0])))));
    for (const d of INVESTMENTS) {
      for (const f of [...(d.start ?? []), ...(d.risk?.fx ?? [])] as Fx[]) {
        expect(FX.has(f[0]) || ['dilute', 'brand', 'rep', 'capacity', 'prod', 'cost'].includes(f[0]), `${d.id}: ${f[0]}`).toBe(true);
        if (f[0] === 'special') expect(SPECIALS[f[1]], `${d.id}: ${f[1]}`).toBeTruthy();
      }
      for (const i of d.inds ?? []) expect(INDUSTRIES[i], `${d.id}: ${i}`).toBeTruthy();
    }
    for (const e of EVENTS) for (const c of [e.cond, ...e.opts.map((o) => o.req)]) if (c?.invest) expect(INV[c.invest], `${e.id}: ${c.invest}`).toBeTruthy();
  });

  it('every flag a card tests is set by something', () => {
    const set = new Set<string>(INVESTMENTS.flatMap((d) => (d.flag ? [d.flag] : [])));
    for (const e of EVENTS) for (const o of e.opts) for (const x of o.out) for (const f of x.fx ?? []) if (f[0] === 'flag') set.add(f[1]);
    for (const e of EVENTS) {
      for (const c of [e.cond, ...e.opts.map((o) => o.req)]) for (const k of [c?.flag, c?.notFlag]) if (k) expect(set.has(k), `${e.id}: ${k}`).toBe(true);
      for (const o of e.opts) for (const x of o.out) if (x.boost?.[0] === 'flag') expect(set.has(String(x.boost[1])), `${e.id}: ${x.boost[1]}`).toBe(true);
    }
  });

  it('card text uses only the templates the engine fills in', () => {
    const KNOWN = new Set(['company', 'city', 'office', 'region', 'rival', 'rivalCeo', 'person', 'role', 'ind', 'loan', 'amount']);
    for (const e of EVENTS) {
      const texts = [e.title, e.text, e.lesson, ...e.opts.flatMap((o) => [o.label, o.hint, ...o.out.map((x) => x.text)])];
      for (const t of texts) for (const m of t.matchAll(/\{(\w+)\}/g)) expect(KNOWN.has(m[1]), `${e.id}: {${m[1]}}`).toBe(true);
    }
  });

  it('every glossary term the engine and UI link to exists (missing ones are dropped silently)', () => {
    const code = [...source('engine/src'), ...source('src')].join('\n');
    const ids = new Set<string>();
    for (const m of code.matchAll(/terms\??:\s*\[([^\]]*)\]/g)) for (const s of m[1].matchAll(/'(\w+)'/g)) ids.add(s[1]);
    // explain(title, text, rows?, terms) and the $/P/N helpers take the term list last
    for (const m of code.matchAll(/(?:explain|\$|\bP|\bN)\([^;]*?,\s*\[((?:'\w+',?\s*)+)\]\)/g)) for (const s of m[1].matchAll(/'(\w+)'/g)) ids.add(s[1]);
    expect(ids.size).toBeGreaterThan(20);
    for (const id of ids) expect(TERM[id], id).toBeTruthy();
  });
});

describe('audit: text agrees with the numbers beside it', () => {
  const WORD: Record<string, number> = { two: 2, three: 3, four: 4, five: 5, six: 6, seven: 7, eight: 8, nine: 9, ten: 10, eleven: 11, twelve: 12, sixteen: 16 };
  /** The share of something an outcome's text claims: "a third", "one in seven", "three in ten", "15%". */
  const claimed = (s: string): number | undefined => {
    const m = s.match(/\b(a third|a fifth|a quarter|half|a tenth)\b|\bone in (\w+)\b|\b(\w+) in ten\b|\b(\d+)%/i);
    if (!m) return undefined;
    if (m[1]) return { 'a third': 1 / 3, 'a fifth': 0.2, 'a quarter': 0.25, half: 0.5, 'a tenth': 0.1 }[m[1].toLowerCase()];
    if (m[2]) return 1 / (WORD[m[2].toLowerCase()] ?? Number(m[2]));
    if (m[3]) return (WORD[m[3].toLowerCase()] ?? Number(m[3])) / 10;
    return Number(m[4]) / 100;
  };

  it('an outcome that says how many leave, or how much is lost, matches its one staff, share or valuation effect', () => {
    let n = 0;
    for (const e of EVENTS) for (const o of e.opts) for (const x of o.out) {
      const fx = (x.fx ?? []).filter((f) => f[0] === 'staff' || f[0] === 'share' || f[0] === 'valuation');
      const c = claimed(x.text);
      if (c === undefined || fx.length !== 1) continue;
      n++;
      // walkout said "A third resign" (15%), the order squeeze "A third of your volume" (20%), a short report "a fifth" (15%)
      expect(Math.abs(Math.abs(fx[0][1] as number) / 100 - c), `${e.id}: "${x.text}" vs ${JSON.stringify(fx[0])}`).toBeLessThanOrEqual(0.035);
    }
    expect(n).toBeGreaterThanOrEqual(4);
  });

  it('a price change an option promises is the one it makes', () => {
    for (const e of EVENTS) for (const o of e.opts) {
      const said = (o.label + ' ' + o.hint).match(/(\d+)% off|(?:cut|raise|up|prices?)[^.]*?(\d+)%/i);
      for (const x of o.out) {
        const p = (x.fx ?? []).filter((f) => f[0] === 'special' && ['priceUp', 'priceDown', 'priceDownRegion'].includes(f[1]));
        if (!said || p.length !== 1 || e.id === 'mfg_big_order') continue; // the counter-offer is 5% off on a third of the output
        // cons_bench offered "work at 20% off" and cut prices 5%
        expect(Math.abs(p[0][2] as number), `${e.id}: "${o.hint}"`).toBe(Number(said[1] ?? said[2]));
      }
    }
  });

  it('named contract lengths and head counts match the effects', () => {
    const out = (id: string, text: RegExp) => EVENT[id].opts.flatMap((o) => o.out).find((x) => text.test(x.text))!;
    expect(out('big_customer', /8% off/).text).toMatch(/^Two years/);
    expect(out('big_customer', /8% off/).fx).toContainEqual(['demand', -1, 8, 'office']);
    expect(out('saas_enterprise', /deal/).text).toContain('two-year');
    expect(out('saas_enterprise', /deal/).fx?.find((f) => f[0] === 'demand')?.[2]).toBe(8);
    // "A dozen join you" when 6 + 2 did
    const hire = out('rival_distress', /join you/);
    const joined = (hire.fx ?? []).filter((f) => f[0] === 'special' && /^add/.test(f[1])).reduce((s, f) => s + (f[2] as number), 0);
    expect(WORD[hire.text.split(' ')[0].toLowerCase()]).toBe(joined);
    // the market crash says how far prices fell; the effect moves investor mood by that much
    expect(EVENT.market_crash.text).toContain('a quarter');
    expect(EVENT.market_crash.opts.every((o) => o.out.every((x) => x.fx?.some((f) => f[0] === 'sentiment' && f[1] === -25)))).toBe(true);
  });

  it('a staged project’s stated odds match its gates', () => {
    for (const d of INVESTMENTS.filter((i) => i.stages)) {
      const m = d.pitch.match(/one (?:chance )?in (\w+)/i);
      if (!m) continue;
      const p = d.stages!.reduce((a, s) => a * s.p, 1);
      // the drug said "one in sixteen" beside a shown 9% chance of reaching the end
      expect(Math.abs(WORD[m[1].toLowerCase()] * p - 1), d.id).toBeLessThan(0.15);
    }
  });

  it('a city that claims the fastest growth has it', () => {
    const top = Math.max(...CITIES.map((c) => c.growth));
    for (const c of CITIES) if (/faster than anywhere|fastest[- ]growing city/i.test(c.blurb)) expect(c.growth, c.id).toBe(top);
  });

  it('the retaliation card does not call a city your home market (it can name another one)', () => {
    const e = EVENT.rival_retaliation;
    for (const t of [e.text, ...e.opts.flatMap((o) => [o.label, o.hint])]) expect(t).not.toMatch(/home/i);
    const g = newGame(opts({ industry: 'retail', city: 'nyc' }));
    expect(fill(g, e.opts[0].hint, { city: 'chi' })).toBe('Defend Chicago on service.');
  });

  it('a card that takes a rival’s share in the city it names does not claim to hit their home market', () => {
    // rivalShare acts in the card's city: in a price war, the city you share with them, not where they are based
    for (const e of EVENTS) for (const o of e.opts) for (const x of o.out) {
      if (!x.fx?.some((f) => f[0] === 'rivalShare')) continue;
      for (const t of [o.label, o.hint, x.text]) expect(t, e.id).not.toMatch(/their home|own turf/i);
    }
  });

  it('challenge goals use no templates (the challenge picker shows them as written)', () => {
    for (const s of SCENARIOS) if (!s.chapter) expect(s.goal.text, s.id).not.toMatch(/\{\w+\}/);
  });

  it('a fixed valuation goal says it is in today’s money, because the bar rises with inflation', () => {
    for (const s of SCENARIOS) if (s.goal.kind === 'valuation' && !s.goal.relative) expect(s.goal.text, s.id).toContain('in today’s money');
    const g = startScenario('phase3', 'Audit');
    for (let i = 0; i < 8 && g.status === 'playing'; i++) { g.queue.length = 0; endTurn(g); }
    expect(goalTarget(g)).toBeGreaterThan(50e6 * 1.01); // a few quarters of inflation
    expect(goalText(g)).toContain('$50M valuation, in today’s money');
    expect(money(goalTarget(g))).not.toBe('$50.0M');
  });

  it('an equity raise at or above the valuation is not labelled a rescue', () => {
    const holder = (fx: Fx) => {
      const g = newGame(opts());
      applyFx(g, [fx], {});
      return g.company.cap.holders[g.company.cap.holders.length - 1];
    };
    expect(holder(['equity', 10, 1.25])).toMatchObject({ name: 'New investors', round: 'Placement' }); // bull run, term sheet, white knight
    expect(holder(['equity', 25, 0.5])).toMatchObject({ name: 'Emergency investors', round: 'Bridge' }); // liquidity crisis
  });
});
